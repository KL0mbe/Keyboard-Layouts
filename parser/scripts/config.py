def get_unicode_char_data(char):
    if not char or len(char) > 1:
        return {"character": char, "code_point": None, "unicode_name": None}

    return {
        "character": char,
        "code_point": f"U+{ord(char):04X}",
        "unicode_name": unicodedata.name(char, None),
    }


def clean_str(string):
    return (
        string.replace("—", "-")
        .replace("–", "-")
        .replace(".", "")
        .replace(" ", "")
        .lower()
        .strip()
    )  # strip gets rid of \n
